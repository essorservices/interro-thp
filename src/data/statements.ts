/*
 * Part I statement bank.
 *
 * Text markup (rendered by src/lib/fmt.ts):
 *   nsg          overlined sg (1 if x = 0, 0 otherwise)
 *   Σ[lo..hi]    big sum with limits (same for Π)
 *   P[i,n]       projection P with sub i and sup n
 *   ^{..} _{..}  superscript / subscript
 * Every false statement carries `fix`: the corrected, true version.
 */

export type Statement = {
  truth: boolean;
  text: string;
  /** Why the statement is true or false. */
  why: string;
  /** For false statements: the corrected (true) statement. */
  fix?: string;
};

const T = (text: string, why: string): Statement => ({ truth: true, text, why });
const F = (text: string, why: string, fix: string): Statement => ({ truth: false, text, why, fix });

